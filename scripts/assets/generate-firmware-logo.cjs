#!/usr/bin/env node
// Render the approved vector lockup into a bounded, allocation-free boot sprite.
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');

const sharp = require('../lib/load-sharp.cjs');
const root = path.resolve(__dirname, '../..');
const sourcePath = 'assets/branding/wayline-logo.svg';
const width = 216;
const height = 52;
const colors = [0x65c7ff, 0x0a84ff, 0xf3f6ff];
const rgb = value => [(value >> 16) & 255, (value >> 8) & 255, value & 255];
const rgb565 = value => ((value >> 19) & 31) << 11 | ((value >> 10) & 63) << 5 | (value >> 3) & 31;

async function main() {
  const source = await fs.readFile(path.join(root, sourcePath), 'utf8');
  const wordmark = /(<path\b[^>]*\bid="wayline-wordmark"[^>]*\bfill=")[^"]+("[^>]*>)/;
  assert(wordmark.test(source), 'Expected the Wayline wordmark');
  // Keep the actual master geometry and wordmark; crop only the outer whitespace.
  const svg = source.replace(/viewBox="[^"]+"/, 'viewBox="320 200 1490 350"')
    .replace(wordmark, '$1#F3F6FF$2');
  const rgba = await sharp(Buffer.from(svg), { density: 72 * width * 4 / 1490 })
    .resize(width, height, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha().raw().toBuffer();
  assert.equal(rgba.length, width * height * 4);
  const pixels = Buffer.alloc(width * height);
  const preview = Buffer.alloc(rgba.length);
  const palette = colors.map(rgb);
  const counts = [0, 0, 0];
  for (let index = 0; index < pixels.length; index++) {
    const coverage = Math.round(rgba[index * 4 + 3] * 15 / 255);
    if (coverage === 0) continue;
    const distances = palette.map(color => color.reduce((sum, channel, offset) =>
      sum + (channel - rgba[index * 4 + offset]) ** 2, 0));
    const ink = distances.indexOf(Math.min(...distances));
    pixels[index] = (ink + 1) * 16 + coverage;
    counts[ink]++;
    preview.set([...palette[ink], coverage * 17], index * 4);
  }
  assert(counts.every(count => count > 100), 'Every logo component must remain visible');
  const encoded = [];
  for (let index = 0; index < pixels.length;) {
    let count = 1;
    while (count < 255 && index + count < pixels.length && pixels[index + count] === pixels[index]) count++;
    encoded.push(count, pixels[index]);
    index += count;
  }
  const decoded = Buffer.concat(Array.from({ length: encoded.length / 2 }, (_, index) =>
    Buffer.alloc(encoded[index * 2], encoded[index * 2 + 1])));
  assert(decoded.equals(pixels), 'RLE must round-trip without changing any pixel');
  assert(encoded.length < 8000, 'Keep the boot artwork within its flash budget');
  const hash = crypto.createHash('sha256').update(source).digest('hex');
  const generated = `// Generated by scripts/assets/generate-firmware-logo.cjs; do not edit.\n`
    + `// Source: ${sourcePath}\n// SHA-256: ${hash}\n`
    + `pub const WIDTH: usize = ${width};\npub const HEIGHT: usize = ${height};\n`
    + `pub const COLORS: [u16; 4] = [0, ${colors.map(value => `0x${rgb565(value).toString(16).padStart(4, '0')}`).join(', ')}];\n`
    + `// Each pair is (run length, palette index in high nibble | 4-bit coverage).\n`
    + `pub static RLE: &[u8] = include_bytes!("../assets/boot-logo.rle");\n`;
  await fs.writeFile(path.join(root, 'firmware/assets/boot-logo.rle'), Buffer.from(encoded));
  await fs.writeFile(path.join(root, 'firmware/src/ui_brand.rs'), generated);
  const previewDir = path.join(root, 'build/cardputer-ui');
  await fs.mkdir(previewDir, { recursive: true });
  await sharp(preview, { raw: { width, height, channels: 4 } }).png()
    .toFile(path.join(previewDir, 'boot-logo.png'));
  console.log(JSON.stringify({ width, height, rle_bytes: encoded.length, ink_pixels: counts, source_sha256: hash }));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
