#!/usr/bin/env python3
"""Generate the UI's OFL-licensed 4-bit glyph subset and typed translation table.

Requires Pillow and fontTools. Normal firmware builds use the committed output.
Source: notofonts/noto-cjk, tag Sans2.004, Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "firmware"
    locales = json.loads((root / "assets/locales.json").read_text(encoding="utf-8"))
    assert list(locales) == ["zh-CN", "zh-TW", "en"], "Locale IDs must match Preferences"
    fields = list(locales["zh-CN"])
    assert all(list(copy) == fields for copy in locales.values()), "Missing/reordered translation"
    # Include version strings and hardware names, plus every keyboard shortcut.
    characters = {chr(code) for code in range(32, 127)}
    for copy in locales.values():
        for value in copy.values():
            characters.update(value)
    chars = sorted(characters, key=ord)
    source = TTFont(args.font)
    cmap = source.getBestCmap()
    assert all(ord(c) in cmap for c in chars), "Font is missing required glyphs"
    copyright_text = next(n.toUnicode() for n in source["name"].names if n.nameID == 0)
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    (root / "assets/font-source.txt").write_text(
        "Wayline UI subset (modified bitmap font), licensed under SIL OFL 1.1 (OFL.txt).\n"
        "Source: https://github.com/notofonts/noto-cjk/tree/Sans2.004\n"
        "Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf\n"
        f"SHA256: {digest}\n{copyright_text}\n"
        "Generated with scripts/assets/generate-ui-font.py; 4-bit coverage, 10/12/18 px.\n",
        encoding="utf-8")
    lines = ["// Generated by scripts/assets/generate-ui-font.py; see assets/OFL.txt and font-source.txt.",
             "pub struct Glyph { pub code: u32, pub offset: usize, pub width: u8, pub advance: u8 }",
             "pub struct Font { pub height: u8, pub glyphs: &'static [Glyph], pub pixels: &'static [u8] }"]
    for size in (10, 12, 18):
        size_chars = chars
        if size == 18:
            # Only the home/welcome/reset headlines use the large font.
            headlines = {chr(code) for code in range(32, 127)}
            for copy in locales.values():
                for field in ("brand", "ready", "waiting", "reset_title"):
                    headlines.update(copy[field])
            size_chars = sorted(headlines, key=ord)
        font = ImageFont.truetype(str(args.font), size)
        data, glyphs = bytearray(), []
        for char in size_chars:
            advance = math.ceil(font.getlength(char))
            width, height = advance + 1, size + 4
            mask = Image.new("L", (width, height))
            ImageDraw.Draw(mask).text((0, size), char, font=font, fill=255, anchor="ls")
            coverage = [(p + 8) // 17 for p in mask.tobytes()]
            offset = len(data)
            for i in range(0, len(coverage), 2):
                data.append((coverage[i] << 4) | (coverage[i + 1] if i + 1 < len(coverage) else 0))
            glyphs.append(f"Glyph {{ code: {ord(char)}, offset: {offset}, width: {width}, advance: {advance} }},")
        (root / f"assets/font-{size}.bin").write_bytes(data)
        lines.append(f"pub static FONT_{size}: Font = Font {{ height: {size + 4}, pixels: include_bytes!(\"../assets/font-{size}.bin\"), glyphs: &[")
        lines.extend(glyphs)
        lines.append("] };")
        print(f"{size}px: {len(size_chars)} glyphs, {len(data)} bytes")
    (root / "src/ui_fonts.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    lines = ["// Generated from assets/locales.json by scripts/assets/generate-ui-font.py.",
             "pub struct Copy {"] + [f"pub {field}: &'static str," for field in fields] + ["}", "pub static COPY: [Copy; 3] = ["]
    for copy in locales.values():
        lines.append("Copy {")
        lines.extend(f"{field}: {json.dumps(copy[field], ensure_ascii=False)}," for field in fields)
        lines.append("},")
    lines.append("];")
    (root / "src/ui_strings.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
