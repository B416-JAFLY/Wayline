use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    generate_locale_table();
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    for file in [
        "assets/app.rc",
        "assets/icon.ico",
        "assets/tray-connected.ico",
        "assets/tray-disconnected.ico",
    ] {
        println!("cargo:rerun-if-changed={file}");
    }
    // Shell loads these IDs from the executable, so missing resources are a
    // build error rather than an application that starts without a tray icon.
    embed_resource::compile("assets/app.rc", embed_resource::NONE)
        .manifest_required()
        .expect("compile Omdrop Windows icon resources");
}

/// Compile the TOML locale files into a typed table with static strings.
/// Building the table here keeps missing or malformed translations out of the
/// shipped binary without requiring a TOML parser at runtime.
fn generate_locale_table() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let locales = [
        ("zh-CN", "ZhCn"),
        ("zh-TW", "ZhTw"),
        ("en-US", "EnUs"),
        ("ja-JP", "JaJp"),
        ("ko-KR", "KoKr"),
        ("fr-FR", "FrFr"),
        ("de-DE", "DeDe"),
        ("es-ES", "EsEs"),
    ];
    let mut tables = Vec::with_capacity(locales.len());

    for (locale, variant) in locales {
        let path = manifest.join("locales").join(format!("{locale}.toml"));
        println!("cargo:rerun-if-changed={}", path.display());
        let source = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
        let table: BTreeMap<String, String> = toml::from_str(&source)
            .unwrap_or_else(|error| panic!("parse {}: {error}", path.display()));
        for key in table.keys() {
            assert!(
                !key.is_empty()
                    && key
                        .chars()
                        .all(|character| character.is_ascii_alphanumeric() || character == '_'),
                "{} contains an invalid key: {key:?}",
                path.display()
            );
        }
        tables.push((locale, variant, table));
    }

    let expected: BTreeSet<_> = tables[0].2.keys().cloned().collect();
    for (locale, _, table) in &tables[1..] {
        let keys: BTreeSet<_> = table.keys().cloned().collect();
        let missing: Vec<_> = expected.difference(&keys).cloned().collect();
        let extra: Vec<_> = keys.difference(&expected).cloned().collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "{locale}.toml must match zh-CN.toml; missing={missing:?}, extra={extra:?}"
        );
    }
    for key in &expected {
        let reference = placeholders(&tables[0].2[key]);
        for (locale, _, table) in &tables[1..] {
            let found = placeholders(&table[key]);
            assert_eq!(
                found, reference,
                "{locale}.toml placeholders differ for {key}: {found:?} != {reference:?}"
            );
        }
    }

    let mut generated = String::from(
        "// @generated by build.rs from apps/desktop/locales/*.toml.\n\
         // Do not edit this file directly; update the TOML locale sources instead.\n\
         #[derive(Clone, Copy, Debug)]\n\
         pub struct Strings {\n",
    );
    for key in &expected {
        generated.push_str(&format!("    pub {key}: &'static str,\n"));
    }
    generated.push_str(
        "}\nimpl Language {\n    pub const fn strings(self) -> Strings {\n        match self {\n",
    );
    for (locale, variant, table) in &tables {
        generated.push_str(&format!("            Self::{variant} => Strings {{\n"));
        for key in &expected {
            let value = table
                .get(key)
                .unwrap_or_else(|| panic!("{locale}.toml is missing key {key}"));
            generated.push_str(&format!("                {key}: {value:?},\n"));
        }
        generated.push_str("            },\n");
    }
    generated.push_str("        }\n    }\n}\n");

    let output =
        Path::new(&env::var_os("OUT_DIR").expect("output directory")).join("i18n_strings.rs");
    fs::write(&output, generated)
        .unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
}

fn placeholders(value: &str) -> BTreeSet<&str> {
    let mut found = BTreeSet::new();
    let mut rest = value;
    while let Some(start) = rest.find('{') {
        let Some(relative_end) = rest[start + 1..].find('}') else {
            break;
        };
        let end = start + 1 + relative_end;
        found.insert(&rest[start + 1..end]);
        rest = &rest[end + 1..];
    }
    found
}
